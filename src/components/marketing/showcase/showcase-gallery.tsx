"use client";

import { AnimatePresence } from "motion/react";
import { Info } from "lucide-react";
import { useEffect, useId, useMemo, useState } from "react";
import { cn } from "@/components/ui/button";
import {
  filterShowcase,
  showcaseFilters,
  type ShowcaseCategory,
  type ShowcaseEntry,
} from "../data/showcase";
import { m } from "../motion/motion";
import { takeShowcaseTarget } from "./showcase-target";
import { VideoCard } from "./video-card";

type Filter = ShowcaseCategory | "all";

export function ShowcaseGallery({
  entries,
  initialFilter = "all",
  priorityCount = 0,
  showFilters = true,
}: {
  entries: ShowcaseEntry[];
  initialFilter?: Filter;
  priorityCount?: number;
  showFilters?: boolean;
}) {
  const uid = useId();
  const [filter, setFilter] = useState<Filter>(initialFilter);
  const visible = useMemo(
    () => filterShowcase(entries, filter),
    [entries, filter],
  );
  // Arriving from a hero poster: scroll to that example without a URL fragment.
  useEffect(() => {
    const id = takeShowcaseTarget();
    if (!id) return;
    const target = document.getElementById(id);
    target?.scrollIntoView({ block: "center" });
  }, []);

  const hasIllustrative = entries.some(
    (entry) => entry.provenance === "illustrative",
  );

  return (
    <div className="flex flex-col gap-8">
      <div className="flex flex-col items-center gap-4">
        {showFilters && (
          <div
            role="group"
            aria-label="Filter examples by format"
            className="flex max-w-full gap-1 overflow-x-auto rounded-2xl border border-(--border) bg-(--surface) p-1 [scrollbar-width:none]"
          >
            {showcaseFilters.map((option) => {
              const selected = option.id === filter;
              const count =
                option.id === "all"
                  ? entries.length
                  : entries.filter((entry) => entry.category === option.id)
                      .length;
              return (
                <button
                  key={option.id}
                  type="button"
                  aria-pressed={selected}
                  disabled={count === 0}
                  onClick={() => setFilter(option.id)}
                  className="mk-tab shrink-0 px-3.5 text-sm"
                >
                  {selected && (
                    <m.span
                      layoutId={`${uid}-filter-pill`}
                      className="mk-tab-indicator"
                      transition={{
                        type: "spring",
                        stiffness: 480,
                        damping: 36,
                      }}
                      aria-hidden="true"
                    />
                  )}
                  <span className="relative z-10">{option.label}</span>
                </button>
              );
            })}
          </div>
        )}
        <p className="sr-only" aria-live="polite">
          Showing {visible.length}{" "}
          {visible.length === 1 ? "example" : "examples"}
        </p>
        {hasIllustrative && (
          <p className="flex items-center gap-2 text-center text-[0.8125rem] text-(--muted)">
            <Info size={14} aria-hidden="true" />
            Illustrative samples show each format. They were not generated by
            Clipvero.
          </p>
        )}
      </div>

      <m.ul
        layout
        className={cn(
          "-mx-4 flex snap-x snap-mandatory gap-4 overflow-x-auto px-4 pb-2 [scrollbar-width:thin]",
          "sm:mx-0 sm:grid sm:snap-none sm:grid-cols-3 sm:overflow-visible sm:px-0 sm:pb-0 lg:grid-cols-4 lg:gap-5",
        )}
      >
        <AnimatePresence mode="popLayout" initial={false}>
          {visible.map((entry, i) => (
            <m.li
              key={entry.id}
              id={entry.id}
              layout
              initial={{ opacity: 0, scale: 0.94, y: 12 }}
              animate={{ opacity: 1, scale: 1, y: 0 }}
              exit={{ opacity: 0, scale: 0.94, transition: { duration: 0.18 } }}
              transition={{ duration: 0.4, delay: Math.min(i, 6) * 0.035 }}
              className="w-[72vw] max-w-[300px] shrink-0 snap-center scroll-mt-28 sm:w-auto sm:max-w-none"
            >
              <VideoCard entry={entry} priority={i < priorityCount} />
            </m.li>
          ))}
        </AnimatePresence>
      </m.ul>
    </div>
  );
}
