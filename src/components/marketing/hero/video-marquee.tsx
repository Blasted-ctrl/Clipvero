import Image from "next/image";
import { Play } from "lucide-react";
import {
  categoryLabel,
  formatDuration,
  type ShowcaseEntry,
} from "../data/showcase";
import { MarqueeLink } from "./marquee-link";

function Tile({ entry, hidden }: { entry: ShowcaseEntry; hidden: boolean }) {
  return (
    <li className="w-[150px] shrink-0 sm:w-[184px]">
      <MarqueeLink
        id={entry.id}
        hidden={hidden}
        className="mk-video-frame mk-lift group block border border-white/[0.07]"
        label={
          hidden
            ? undefined
            : `${entry.title}, ${categoryLabel[entry.category]} sample`
        }
      >
        <Image
          src={entry.poster}
          alt=""
          fill
          sizes="184px"
          className="mk-zoom-img"
        />
        <span className="mk-video-scrim absolute inset-0" aria-hidden="true" />
        <span className="mk-badge mk-badge-overlay absolute left-2 top-2 text-[0.625rem]">
          {categoryLabel[entry.category]}
        </span>
        <span
          className="absolute inset-0 flex items-center justify-center opacity-0 transition-opacity duration-300 group-hover:opacity-100"
          aria-hidden="true"
        >
          <span className="flex size-11 items-center justify-center rounded-full bg-white/90 text-black">
            <Play size={18} fill="currentColor" className="translate-x-0.5" />
          </span>
        </span>
        <span className="absolute inset-x-0 bottom-0 flex items-end justify-between gap-2 p-3 text-left">
          <span className="line-clamp-2 text-[0.8125rem] font-semibold leading-snug text-white">
            {entry.title}
          </span>
          <span className="mk-mono text-[0.6875rem] text-white/75">
            {formatDuration(entry.durationSeconds)}
          </span>
        </span>
      </MarqueeLink>
    </li>
  );
}

/** Browsable format strip. Native scrolling also works with touch and keyboard focus. */
export function VideoMarquee({ entries }: { entries: ShowcaseEntry[] }) {
  return (
    <div className="flex flex-col items-center gap-4">
      <div className="mk-marquee w-full">
        <ul className="mk-marquee-track py-2" aria-label="Example formats">
          {entries.map((entry) => (
            <Tile key={entry.id} entry={entry} hidden={false} />
          ))}
        </ul>
      </div>
      <p className="px-4 text-center text-[0.8125rem] text-(--muted)">
        Format studies. Illustrative samples, not generated by Clipvero.
      </p>
    </div>
  );
}
